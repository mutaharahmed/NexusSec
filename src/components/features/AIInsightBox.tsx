"use client";

import * as React from "react";
import { Sparkles, ShieldAlert, CheckCircle2, Copy, Check, Terminal } from "lucide-react";
import { Card, CardHeader, CardTitle, CardContent, CardFooter } from "@/components/ui/card";
import { Badge } from "@/components/ui/badge";
import { Skeleton } from "@/components/ui/skeleton";
import { Button } from "@/components/ui/button";

interface AIInsightBoxProps {
  isLoading: boolean;
  summary: string | null;
  recommendations?: string[];
  iocCount?: number;
}

export function AIInsightBox({
  isLoading,
  summary,
  recommendations = [],
  iocCount = 0,
}: AIInsightBoxProps) {
  const [copied, setCopied] = React.useState(false);

  const handleCopy = () => {
    if (!summary) return;
    const textToCopy = `NEXUSSEC AI INCIDENT SUMMARY\n\n${summary}\n\nRecommended Actions:\n${recommendations
      .map((r, i) => `${i + 1}. ${r}`)
      .join("\n")}`;
    navigator.clipboard.writeText(textToCopy);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  if (isLoading) {
    return (
      <Card className="border border-ai-accent/40 bg-gradient-to-br from-ai-accent/10 via-background to-card shadow-lg shadow-ai-accent/5 overflow-hidden">
        <CardHeader className="pb-3 border-b border-ai-accent/20">
          <div className="flex items-center justify-between">
            <div className="flex items-center gap-2">
              <div className="p-2 rounded-lg bg-ai-accent/20 text-ai-accent animate-pulse">
                <Sparkles className="h-5 w-5" />
              </div>
              <div>
                <Skeleton className="h-5 w-48 mb-1" />
                <Skeleton className="h-3 w-32" />
              </div>
            </div>
            <Skeleton className="h-6 w-24 rounded-full" />
          </div>
        </CardHeader>
        <CardContent className="pt-4 space-y-3">
          <Skeleton className="h-4 w-full" />
          <Skeleton className="h-4 w-[92%]" />
          <Skeleton className="h-4 w-[75%]" />
          <div className="pt-2 space-y-2">
            <Skeleton className="h-4 w-40" />
            <Skeleton className="h-8 w-full rounded-md" />
            <Skeleton className="h-8 w-full rounded-md" />
          </div>
        </CardContent>
        <CardFooter className="pt-2 text-xs text-muted-foreground flex items-center justify-between border-t border-border/50 bg-muted/20">
          <span className="flex items-center gap-1">
            <Terminal className="h-3.5 w-3.5 text-ai-accent animate-spin" />
            Synthesizing multi-vector incident intelligence...
          </span>
          <span>Generated by NexusSec AI</span>
        </CardFooter>
      </Card>
    );
  }

  if (!summary) {
    return null;
  }

  return (
    <Card className="relative overflow-hidden border border-ai-accent/50 bg-gradient-to-br from-ai-accent/10 via-background to-card shadow-xl shadow-ai-accent/10 transition-all">
      {/* Top accent glow line */}
      <div className="absolute top-0 left-0 right-0 h-[2px] bg-gradient-to-r from-transparent via-ai-accent to-transparent" />

      <CardHeader className="pb-3 border-b border-ai-accent/20">
        <div className="flex flex-wrap items-center justify-between gap-2">
          <div className="flex items-center gap-2.5">
            <div className="p-2 rounded-lg bg-ai-accent/20 text-ai-accent ring-1 ring-ai-accent/40 shadow-sm shadow-ai-accent/30">
              <Sparkles className="h-5 w-5 animate-pulse-subtle" />
            </div>
            <div>
              <CardTitle className="text-base sm:text-lg flex items-center gap-2 font-bold tracking-tight">
                AI Incident Summary
                <Badge variant="ai" className="text-[10px] uppercase font-mono tracking-widest px-2 py-0.5">
                  Live Intelligence
                </Badge>
              </CardTitle>
              <p className="text-xs text-muted-foreground">
                Synthesized from {iocCount} analyzed threat indicator{iocCount === 1 ? "" : "s"}
              </p>
            </div>
          </div>

          <Button
            variant="outline"
            size="sm"
            onClick={handleCopy}
            className="h-8 text-xs gap-1.5 border-ai-accent/30 hover:bg-ai-accent/10 hover:text-ai-accent"
          >
            {copied ? (
              <>
                <Check className="h-3.5 w-3.5 text-emerald-400" />
                Copied Report
              </>
            ) : (
              <>
                <Copy className="h-3.5 w-3.5" />
                Copy Brief
              </>
            )}
          </Button>
        </div>
      </CardHeader>

      <CardContent className="pt-4 space-y-4">
        {/* Executive summary paragraph */}
        <p className="text-sm leading-relaxed text-foreground/90 font-sans font-medium">
          {summary}
        </p>

        {/* Recommended Actions */}
        {recommendations.length > 0 && (
          <div className="rounded-lg border border-border/70 bg-card/60 p-3.5 space-y-2.5">
            <div className="flex items-center gap-1.5 text-xs font-semibold uppercase tracking-wider text-muted-foreground">
              <ShieldAlert className="h-3.5 w-3.5 text-ai-accent" />
              Recommended Containment Actions
            </div>
            <ul className="space-y-1.5 text-xs">
              {recommendations.map((action, idx) => (
                <li
                  key={idx}
                  className="flex items-start gap-2 text-foreground/80 font-mono leading-normal bg-background/50 p-1.5 rounded border border-border/40"
                >
                  <CheckCircle2 className="h-3.5 w-3.5 text-emerald-400 mt-0.5 shrink-0" />
                  <span>{action}</span>
                </li>
              ))}
            </ul>
          </div>
        )}
      </CardContent>

      <CardFooter className="py-2.5 px-6 text-xs text-muted-foreground flex items-center justify-between border-t border-border/40 bg-muted/20">
        <span className="flex items-center gap-1 font-mono text-[11px]">
          <span className="inline-block h-1.5 w-1.5 rounded-full bg-emerald-400 animate-pulse" />
          Autonomous correlation verified
        </span>
        <span className="font-semibold text-foreground/80 tracking-wide text-[11px]">
          Generated by NexusSec AI
        </span>
      </CardFooter>
    </Card>
  );
}
